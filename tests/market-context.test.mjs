import {mkdtempSync,readFileSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createRequire} from 'node:module';
import ts from 'typescript';
import assert from 'node:assert/strict';
const out=join(mkdtempSync(join(tmpdir(),'market-context-tests-')),'market-context.cjs');
writeFileSync(out,ts.transpileModule(readFileSync(new URL('../src/lib/market-context.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText);
const {emptyMarketContext,calculateSentiment,movementToScore,sentimentLabel,altcoinSeasonLabel,isMetricStale,normalizeMarketContext}=createRequire(import.meta.url)(out);
const context=structuredClone(emptyMarketContext);
context.fearGreed.value=80;context.market.btcChange24h=2;context.market.marketCapChange24h=-2;
assert.equal(calculateSentiment(context),65);
assert.equal(movementToScore(10),100);assert.equal(movementToScore(-10),0);assert.equal(movementToScore(0),50);
assert.equal(sentimentLabel(20),'EXTREMT RÄDD');assert.equal(sentimentLabel(35),'RÄDD');assert.equal(sentimentLabel(50),'NEUTRAL');assert.equal(sentimentLabel(65),'GIRIG');assert.equal(sentimentLabel(90),'EXTREMT GIRIG');
assert.equal(altcoinSeasonLabel(25),'BITCOIN SEASON');assert.equal(altcoinSeasonLabel(26),'NEUTRAL');assert.equal(altcoinSeasonLabel(74),'NEUTRAL');assert.equal(altcoinSeasonLabel(75),'ALTCOIN SEASON');
assert.equal(calculateSentiment(emptyMarketContext),null);assert.equal(isMetricStale(null,1000),true);
const normalized=normalizeMarketContext({schemaVersion:1,fearGreed:{value:150},market:{btcDominance:60},altcoinSeason:{value:48}});
assert.equal(normalized.fearGreed.value,null);assert.equal(normalized.market.btcDominance,60);assert.equal(normalized.altcoinSeason.value,48);
console.log('Market context checks passed: weighted sentiment, all five labels, altcoin thresholds, missing data and input validation.');
