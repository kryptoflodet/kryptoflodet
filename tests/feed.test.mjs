import { createRequire } from 'node:module';
import { mkdtempSync,readFileSync,writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import ts from 'typescript';
import assert from 'node:assert/strict';
const out=mkdtempSync(join(tmpdir(),'kryptoflodet-tests-'));
for(const f of ['types','feed','demo']) writeFileSync(join(out,f+'.js'),ts.transpileModule(readFileSync(new URL('../src/lib/'+f+'.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText);
const require=createRequire(import.meta.url);
const {filterNews,deduplicate,assessEvidence,trending}=require(join(out,'feed.js'));
const {demoNews,sources}=require(join(out,'demo.js'));
assert.equal(filterNews(demoNews,{coin:'SUI'}).length,2);
assert.equal(filterNews(demoNews,{q:'Michael Saylor'}).length,1);
assert.ok(filterNews(demoNews,{noise:'confirmed'}).every(n=>n.status==='confirmed'));
assert.ok(filterNews(demoNews,{noise:'important'}).every(n=>n.importance>=3&&n.status!=='rumor'));
assert.equal(filterNews(demoNews,{q:'does-not-exist'}).length,0);
assert.equal(filterNews(demoNews,{sort:'importance'})[0].importance,5);
const n=demoNews[0];
const duplicated={...n,id:'copy',sourceId:'coindesk',evidence:[{sourceId:'coindesk',url:'https://www.coindesk.com/story',direct:false,verified:true,originId:'shared'}]};
const grouped=deduplicate([n,duplicated],sources);
assert.equal(grouped.length,1);assert.equal(grouped[0].sourceId,'sec');assert.equal(grouped[0].evidence.length,3);
const echoes={...n,status:'unconfirmed',evidence:[{sourceId:'coindesk',url:'https://example.com/1',direct:true,verified:true,originId:'shared'},{sourceId:'strategy',url:'https://example.com/2',direct:false,verified:true,originId:'shared'}]};
assert.equal(assessEvidence(echoes,sources).status,'unconfirmed','Copies cannot confirm a rumor');
assert.equal(assessEvidence({...n,evidence:[{sourceId:'sec',url:'https://www.sec.gov',direct:true,verified:false,originId:'1'}]},sources).status,'unconfirmed','Official identity alone cannot verify claims');
assert.equal(assessEvidence(n,sources).status,'confirmed');
assert.equal(deduplicate([{...n,eventKey:'event-a'},{...n,id:'second',eventKey:'event-b'}],sources).length,2,'Same coin is not the same event');
assert.equal(trending(demoNews)[0][0],'Bitcoin');
assert.ok(demoNews.every(n=>n.demo&&n.originalText.includes('Illustrative')));
console.log('14 feed assertions passed: search, coin filters, verification, importance, deduplication, source independence, trends, demo labeling.');
