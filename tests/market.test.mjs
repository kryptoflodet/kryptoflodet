import {mkdtempSync,readFileSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createRequire} from 'node:module';
import ts from 'typescript';
import assert from 'node:assert/strict';
const out=join(mkdtempSync(join(tmpdir(),'market-tests-')),'market.cjs');
writeFileSync(out,ts.transpileModule(readFileSync(new URL('../src/lib/market.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText);
const {trackedCoins,normalizeMarket}=createRequire(import.meta.url)(out);
const now=Date.now();
const fixture=Object.fromEntries(trackedCoins.map(([id])=>[id,{usd:.123456,sek:1.15,usd_24h_change:-1.2,sek_24h_change:0,last_updated_at:Math.floor(now/1000)}]));
const data=normalizeMarket(fixture,now);
assert.equal(data.mode,'live');assert.equal(data.quotes.length,15);
assert.deepEqual(data.quotes.map(q=>q.symbol),['BTC','ETH','SOL','SUI','HBAR','ONDO','XRP','ADA','DOGE','XLM','AVAX','LINK','BNB','HYPE','LTC']);
assert.equal(data.quotes[0].priceSek,1.15);assert.equal(data.quotes[0].changeSek24h,0);
assert.equal(normalizeMarket(fixture,now+360000).mode,'stale');
delete fixture.bitcoin;
const missing=normalizeMarket(fixture,now);assert.equal(missing.mode,'stale');assert.equal(missing.quotes[0].price,null);
fixture.ethereum.usd=NaN;assert.equal(normalizeMarket(fixture,now).quotes[1].price,null);
assert.throws(()=>normalizeMarket({},now));
console.log('Market checks passed: all 15 mappings, SEK, zero change, stale data, missing and invalid prices.');
