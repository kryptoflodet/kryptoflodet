import {mkdtempSync,readFileSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createRequire} from 'node:module';
import ts from 'typescript';
import assert from 'node:assert/strict';
const dir=mkdtempSync(join(tmpdir(),'chart-tests-'));
for(const name of ['chart','market'])writeFileSync(join(dir,name+'.js'),ts.transpileModule(readFileSync('src/lib/'+name+'.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText);
const {rangeStart,normalizePoints,fetchChart,chartRanges}=createRequire(import.meta.url)(join(dir,'chart.js'));
const now=Date.parse('2026-10-11T15:00:00Z');
assert.equal(rangeStart('24h',now),now-86400000);
assert.equal(rangeStart('today',now),Date.parse('2026-10-10T22:00:00Z'));
assert.equal(rangeStart('ytd',now),Date.parse('2025-12-31T23:00:00Z'));
assert.equal(rangeStart('max',now),0);assert.equal(chartRanges.length,10);
assert.deepEqual(normalizePoints([[now-1,1],[now-2,2],[now-1,3],[now,NaN],[now+900000,6],[now-5,-2]],now),[[now-2,2],[now-1,3]]);
assert.throws(()=>normalizePoints([[now,1]],now));
let calls=[];globalThis.fetch=async url=>{calls.push(String(url));if(String(url).includes('coingecko'))return {ok:false};return {ok:true,json:async()=>[[Date.now()-86400000,'1','1','1','100','1',Date.now()-3600000],[Date.now()-3600000,'1','1','1','105','1',Date.now()]]};};
const fallback=await fetchChart('BTC','week','SEK',new AbortController().signal);
assert.equal(fallback.unit,'USDT');assert.equal(fallback.source,'Binance');assert.ok(calls[1].includes('BTCUSDT'));assert.equal(fallback.points.at(-1)[1],105);
const long=await fetchChart('ETH','5y','USD',new AbortController().signal);assert.equal(long.unit,'USDT');assert.ok(calls.at(-1).includes('interval=1w'));
await assert.rejects(()=>fetchChart('UNKNOWN','week','USD',new AbortController().signal));
console.log('Chart tests passed: ranges, Stockholm dates, data validation and explicit fallback currency.');
