import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
const app=readFileSync('src/App.tsx','utf8');
assert.ok(!app.includes("fetch('/api/"),'Pages must not call nonexistent server routes');
assert.ok(!app.includes('href="/"'),'Home links must respect repository base');
assert.ok(!app.includes('/images/'),'Images must respect repository base');
assert.doesNotMatch(app,/Spara nyhet|Spara X-inlägg|Viktigast just nu/,'Feed no longer shows save controls or the removed top section');
assert.match(readFileSync('vite.config.ts','utf8'),/base:\s*'\.\/'/);
assert.ok(existsSync('package-lock.json'),'npm ci needs the lockfile');

const html=readFileSync('dist/index.html','utf8');
const sourceHtml=readFileSync('index.html','utf8');
assert.match(html,/src="\.\/assets\//);
assert.match(html,/href="\.\/favicon\.svg"/);
assert.match(sourceHtml,/<title>Kryptopuls – Kryptonyheter, Bitcoin &amp; marknaden i realtid<\/title>/);
assert.match(sourceHtml,/rel="canonical" href="https:\/\/kryptopuls\.se\/"/);
assert.match(sourceHtml,/property="og:image" content="https:\/\/kryptopuls\.se\/images\/kryptopuls-social\.png"/);
assert.match(sourceHtml,/name="twitter:image" content="https:\/\/kryptopuls\.se\/images\/kryptopuls-social\.png"/);
assert.match(sourceHtml,/"@type": "Organization"/);
assert.match(readFileSync('scripts/build-pages.py','utf8'),/DOMAIN='https:\/\/kryptopuls\.se'/);
assert.match(readFileSync('scripts/build-pages.py','utf8'),/images\/kryptopuls-social\.png/);
assert.ok(existsSync('public/images/kryptopuls-social.png'),'Kryptopuls social preview image is available to Pages build');
assert.ok(!existsSync('public/images/kryptokollen-social.png'),'Old branded social preview was removed');
assert.equal(readFileSync('public/CNAME','utf8').trim(),'kryptopuls.se');
assert.equal(readFileSync('dist/CNAME','utf8').trim(),'kryptopuls.se');

const manifest=JSON.parse(readFileSync('dist/manifest.webmanifest','utf8'));
assert.equal(manifest.name,'Kryptopuls – kryptomarknaden på svenska');
assert.ok(manifest.icons.some(icon=>icon.src==='/icon-192.png'));
assert.ok(existsSync('dist/apple-touch-icon.png'));
assert.ok(existsSync('dist/icon-512.png'));
const staticPage=readFileSync('dist/kategori/bitcoin/index.html','utf8');
assert.match(staticPage,/canonical" href="https:\/\/kryptopuls\.se\/kategori\/bitcoin\//);
assert.match(staticPage,/og:site_name" content="Kryptopuls/);
assert.match(staticPage,/Kryptomarknaden\. På svenska\. I realtid\./);
assert.doesNotMatch(sourceHtml,/Kryptokollen|kryptokollen/i);

for(const name of ['bitcoin-news','ethereum','network','institutions'])for(const width of [640,1280])assert.ok(existsSync(`dist/images/${name}-${width}.webp`));
assert.ok(existsSync('dist/images/bitcoin.svg'),'Bitcoin logo source is included in the Pages build');
assert.ok(existsSync('dist/data/market-context.json'),'Market context snapshot is shipped on the same origin');
assert.match(readFileSync('dist/data/market-context.json','utf8'),/"schemaVersion":\s*1/);
console.log('Pages checks passed: Kryptopuls metadata, custom domain, assets, manifest, static SEO and existing Pages behavior.');
